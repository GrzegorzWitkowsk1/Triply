import { test, expect, login, openTrip } from "./fixtures.ts";

test.use({ scenario: "journey", locale: "en-US" });

test("saved-trip Journey persists automatic spending, locks, undo, manual prompts and skipped progress", async ({ page, user, harness }) => {
  await login(page, user); await openTrip(page, user.tripId!);
  await expect(page.getByRole("button", { name: "Plan mode", exact: true })).toHaveAttribute("aria-pressed", "true");
  const before = await harness.state();
  await page.getByRole("button", { name: "Journey mode", exact: true }).click();
  await expect(page.locator(".journey-day")).toBeVisible();
  await page.getByRole("button", { name: "Mark Barcelona Cathedral as visited", exact: true }).click();
  await expect(page.getByText(/Visited · .*60.* added to expenses/)).toBeVisible();
  await expect(page.getByText("Add an expense for this visit?")).toHaveCount(0);
  await expect(page.locator(".journey-place.is-visited")).toHaveCount(1);
  await expect(page.locator(".trip-marker[aria-label*='Barcelona Cathedral'][aria-label*='Visited']")).toHaveCount(1);
  await expect(page.getByRole("progressbar", { name: "Trip progress" })).toHaveAttribute("value", "12.5");
  let stored = await harness.trip(user.tripId!);
  expect(stored.expenses.filter(expense => expense.automaticSource)).toHaveLength(1);
  expect(stored.expenses.find(expense => expense.automaticSource)?.amountMinor).toBe(6000);
  await page.reload();
  await expect(page.locator(".journey-place.is-visited")).toHaveCount(1);
  expect((await harness.trip(user.tripId!)).expenses).toHaveLength(2);
  await page.getByRole("button", { name: "Plan mode", exact: true }).click();
  await expect(page.locator(".trip-timeline")).toBeVisible();
  await expect(page.getByRole("button", { name: "Edit Barcelona Cathedral", exact: true })).toBeDisabled();
  await expect(page.getByRole("button", { name: "Reorder Barcelona Cathedral", exact: true })).toBeDisabled();
  await expect(page.locator(".timeline-item.is-visited")).toHaveCount(1);
  await page.getByRole("button", { name: "Reset Barcelona Cathedral to planned", exact: true }).click();
  await expect(page.getByRole("button", { name: "Edit Barcelona Cathedral", exact: true })).toBeEnabled();
  expect((await harness.trip(user.tripId!)).expenses).toHaveLength(2);
  await page.getByRole("button", { name: "Edit Barcelona Cathedral", exact: true }).click();
  await page.getByRole("menuitem", { name: "Move later", exact: true }).click();
  await expect(page.locator(".activity-name").first()).toHaveText("Palau de la Musica");
  await page.getByRole("button", { name: "Journey mode", exact: true }).click();
  await expect(page.locator(".journey-day")).toBeVisible();
  await page.getByRole("button", { name: "Mark Barcelona Cathedral as visited", exact: true }).click();
  await expect(page.locator(".journey-place.is-visited")).toHaveCount(1);
  expect((await harness.trip(user.tripId!)).expenses).toHaveLength(2);
  await page.getByRole("button", { name: "Mark Palau de la Musica as visited", exact: true }).click();
  await expect(page.getByText(/Visited · .*80.* added to expenses/)).toBeVisible();
  stored = await harness.trip(user.tripId!);
  expect(stored.expenses.filter(expense => expense.automaticSource).map(expense => expense.amountMinor).sort()).toEqual([6000, 8000]);
  await page.getByRole("button", { name: "Mark Gothic Quarter as visited", exact: true }).click();
  await expect(page.getByText("Add an expense for this visit?")).toBeVisible();
  await page.getByRole("checkbox", { name: "Don't ask again. I'll add expenses manually." }).check();
  await page.getByRole("button", { name: "Not now", exact: true }).click();
  await page.getByRole("button", { name: "Mark SITAKE YA as skipped", exact: true }).click();
  await expect(page.locator(".journey-place.is-skipped")).toHaveCount(1);
  await expect(page.getByRole("progressbar", { name: "Day progress" })).toHaveAttribute("value", "75");
  await page.getByRole("tab").nth(1).click();
  await page.getByRole("button", { name: "Mark Roman Walls as visited", exact: true }).click();
  await expect(page.locator(".journey-place.is-visited")).toHaveCount(1);
  await expect(page.getByText("Add an expense for this visit?")).toHaveCount(0);
  await page.reload();
  await expect(page.getByRole("tab").nth(1)).toHaveAttribute("aria-selected", "true");
  await expect(page.locator(".journey-place.is-visited")).toHaveCount(1);
  expect((await harness.trip(user.tripId!)).expenses.filter(expense => expense.automaticSource)).toHaveLength(2);
  await page.getByRole("button", { name: "Correct expense for Barcelona Cathedral", exact: true }).click();
  const correction = page.getByRole("dialog", { name: "Correct admission expense" });
  await correction.getByRole("textbox", { name: "Amount", exact: true }).fill("50.00");
  await correction.getByRole("button", { name: "Save changes", exact: true }).click();
  await expect(correction).toHaveCount(0);
  stored = await harness.trip(user.tripId!);
  expect(stored.expenses.find(expense => expense.automaticSource?.itineraryItemId === stored.itinerary!.days[0].activities.find(item => item.title === "Barcelona Cathedral")!.itineraryItemId)).toMatchObject({ amountMinor: 5000, automaticSource: { postedAmountMinor: 6000 } });
  const after = await harness.state();
  expect(after.calls.filter(call => /places|attractions|ai:/i.test(call))).toEqual(before.calls.filter(call => /places|attractions|ai:/i.test(call)));
});

test("mobile status controls, navigation and bilingual lock explanations remain accessible", async ({ page, user }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await login(page, user); await openTrip(page, user.tripId!);
  await page.getByRole("button", { name: "Journey mode", exact: true }).focus();
  await page.keyboard.press("Enter");
  await expect(page.locator(".journey-day")).toBeVisible();
  await page.getByRole("button", { name: "Mark Barcelona Cathedral as visited", exact: true }).click();
  await expect(page.locator(".journey-place.is-visited")).toBeVisible();
  await expect(page.getByRole("link", { name: /Navigate to Barcelona Cathedral/ })).toHaveAttribute("href", /destination=/);
  await page.getByRole("button", { name: "Plan mode", exact: true }).click();
  await expect(page.locator(".trip-timeline")).toBeVisible();
  await expect(page.getByRole("button", { name: "Edit Barcelona Cathedral", exact: true })).toBeDisabled();
  await expect(page.getByText("Editing locked. Reset this visit to planned to change its itinerary.")).toBeVisible();
  await page.getByRole("button", { name: /^Language:/ }).click();
  await page.getByRole("menuitemradio", { name: "Polski", exact: true }).click();
  await expect(page.getByText("Edycja zablokowana. Cofnij wizytę do planowanej, aby zmienić jej plan.")).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.setViewportSize({ width: 320, height: 844 });
  const overflow = await page.evaluate(() => [...document.querySelectorAll<HTMLElement>("main *")].filter(element => element.getBoundingClientRect().right > innerWidth + 1)
    .map(element => ({ tag: element.tagName, className: element.className, right: element.getBoundingClientRect().right, text: element.textContent?.slice(0, 50) })));
  expect(overflow, "Journey controls must fit at 320px in Polish").toEqual([]);
});
